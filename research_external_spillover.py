def parse(s):
    out = []
    for line in s.strip().split("\n"):
        d, c = line.split(",")
        out.append((d, float(c)))
    return out

cn, us = parse(CN), parse(US)
us_dates = [d for d, _ in us]
us_close = dict(us)

def us_prev_trade_day(target):
    # 找美股中日期 < target 的最近交易日（隔夜外盘）
    cand = [d for d in us_dates if d < target]
    return cand[-1] if cand else None

# 构建配对: A股D日收益 vs 隔夜美股收益
pairs = []  # (date, us_ret, cn_ret)
for i in range(1, len(cn)):
    d, c = cn[i]
    _, cprev = cn[i-1]
    utd = us_prev_trade_day(d)
    if utd is None:
        continue
    # 美股utd的前一交易日
    idx = us_dates.index(utd)
    if idx == 0:
        continue
    uprev = us_close[us_dates[idx-1]]
    us_ret = (us_close[utd] / uprev - 1) * 100
    cn_ret = (c / cprev - 1) * 100
    pairs.append((d, us_ret, cn_ret))

def corr(xs, ys):
    n = len(xs)
    mx, my = sum(xs)/n, sum(ys)/n
    num = sum((x-mx)*(y-my) for x, y in zip(xs, ys))
    den = (sum((x-mx)**2 for x in xs) * sum((y-my)**2 for y in ys)) ** 0.5
    return num/den if den else 0

print("样本数:", len(pairs))
us_r = [p[1] for p in pairs]
cn_r = [p[2] for p in pairs]
print("全样本相关系数 corr(隔夜纳指, 沪深300当日): %.3f" % corr(us_r, cn_r))
# 前半/后半（样本外稳定性）
half = len(pairs)//2
print("前半相关: %.3f  后半相关: %.3f" % (
    corr([p[1] for p in pairs[:half]], [p[2] for p in pairs[:half]]),
    corr([p[1] for p in pairs[half:]], [p[2] for p in pairs[half:]])))

print("\n分组：按隔夜纳指涨跌看A股当日均值")
buckets = [(-99,-2),(-2,-1),(-1,0),(0,1),(1,2),(2,99)]
for lo, hi in buckets:
    sel = [p[2] for p in pairs if lo <= p[1] < hi]
    if sel:
        win = 100*sum(1 for x in sel if x>0)/len(sel)
        print("  纳指[%+d,%+d)%%: n=%3d A股当日均值%+.3f%% 胜率%.0f%%" % (lo, hi, len(sel), sum(sel)/len(sel), win))

print("\n筛子回测：隔夜纳指大跌就空仓，看能否改善")
for thr in (-2, -3, -1.5):
    stay = [p[2] for p in pairs]
    filtered = [p[2] for p in pairs if p[1] >= thr]  # 外盘差于thr则跳过
    skipn = len(stay) - len(filtered)
    print("  阈值纳指<%+.1f%%: 跳过%d天 全样本日均%+.3f%% -> 过滤后%+.3f%%" % (
        thr, skipn, sum(stay)/len(stay), sum(filtered)/len(filtered) if filtered else 0))
